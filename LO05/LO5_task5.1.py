# Task Sheet No. 5.1: Apply Logical Conditions and Operators
# Description: Create logical conditions using comparison and logical operators

# Initialize variables
a = 5
b = 10

# Comparison Operators
print("a > b  :", a > b)
print("a < b  :", a < b)
print("a == b :", a == b)
print("a != b :", a != b)
print("a <= b :", a <= b)
print("a >= b :", a >= b)

# Logical Operators
print("a < b and b == 10 :", a < b and b == 10)
print("a > b or b == 10  :", a > b or b == 10)
print("not a > b          :", not a > b)

