# Task Sheet No. 4.5: Implement Escape Characters in Python Strings
# Description: Apply Python escape characters to produce formatted text output

# 1. New line escape sequence (\n)
print("Python\nProgramming")

# 2. Tab escape sequence (\t)
print("Name\tAge\tCourse")
print("Dara\t20\tPython")

# 3. Quotation mark escape sequences (\")
print("He said, \"Python is easy.\"")

# 4. Backslash escape sequence (\\)
print("C:\\Python\\Projects")

'''
Sample Output:
Python
Programming
Name	Age	Course
Dara	20	Python
He said, "Python is easy."
C:\Python\Projects
'''
