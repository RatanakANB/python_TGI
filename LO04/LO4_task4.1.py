# Task Sheet No. 4.1: Create, Display and Access Python Strings
# Description: Practice basic string creation, display, multiline strings and character indexing

# Create a string variable
course = "Python"

# Display the string
print(course)

# Create a multiline string
message = """Welcome to Python.
Learn string handling.
Practice Python programming."""
print(message)

# Access individual characters using positive and negative indexing
print(course[0])
print(course[1])
print(course[3])
print(course[-1])
print(course[-2])

