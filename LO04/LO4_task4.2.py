# Task Sheet No. 4.2: Apply String Slicing and Determine String Length
# Description: Extract required portions of strings using slicing and determine the number of characters in a string

# Create string variable
course = "Python Programming"

# Slicing operations
print(course[0:6])
print(course[:6])
print(course[7:])
print(course[-11:])

# Determine string length
print(len(course))

'''
Sample Output:
Python
Python
Programming
Programming
18
'''
