# Task Sheet No. 3.3: Implement Python Boolean and Operators

a = 5
b = 10

# Arithmetic Operators
print("Addition:", a + b)
print("Subtraction:", b - a)
print("Multiplication:", a * b)
print("Division:", b / a)
print("Modulus:", b % a)
print("Exponent:", a ** 2)

# Comparison Operators
print("A < B:", a < b)
print("A > B:", a > b)
print("A == B:", a == b)
print("A != B:", a != b)

# Logical Operators
print("Logical AND:", a < b and b == 10)
print("Logical OR:", a > b or b == 10)
print("Logical NOT:", not a > b)

