# Task Sheet No. 3.2: Specify Python Variable Types
# Description: Identify and convert Python variable types

number_text = "25"
age = 20
price = 50

# Type Conversions
number = int(number_text)
age_float = float(age)
price_text = str(price)

# Display results and new types
print(number, type(number))
print(age_float, type(age_float))
print(price_text, type(price_text))

'''
Sample Output:
25 <class 'int'>
20.0 <class 'float'>
50 <class 'str'>
'''
