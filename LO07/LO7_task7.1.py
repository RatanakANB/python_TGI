# Description: Create Python tuples and retrieve elements using positive and negative indexing.

students = ("Dara", "Sokha", "Vanna", "Malis", "Ratha")

print("Complete tuple:", students)
print("First student (index 0)   :", students[0])
print("Third student (index 2)   :", students[2])
print("Last student (index -1)   :", students[-1])
print("Second to last (index -2) :", students[-2])

